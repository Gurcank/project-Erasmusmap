import fs from "node:fs";
import path from "node:path";
import { config as loadEnv } from "dotenv";
import { PrismaClient } from "@prisma/client";

// Works whether this runs through `prisma db seed`, which loads the env via
// prisma.config.ts, or directly through ts-node, which does not.
loadEnv({ path: ".env.local", quiet: true });

const prisma = new PrismaClient();

// Inserting one row at a time would mean thousands of round trips; chunking
// keeps the seed to a handful of statements without one enormous query.
const CHUNK_SIZE = 500;

type SeedCity = {
  geonameId: number;
  name: string;
  slug: string;
  country: string;
  latitude: number;
  longitude: number;
  population: number;
  searchAliases: string[];
};

// Read rather than import: a JSON import needs an import attribute under ESM,
// which breaks depending on how the seed is invoked.
function loadCities(): SeedCity[] {
  const file = path.join("prisma", "data", "cities.json");
  return JSON.parse(fs.readFileSync(file, "utf8")) as SeedCity[];
}

/**
 * Seeds the city list from prisma/data/cities.json, generated by
 * scripts/build-city-data.ts from a GeoNames dump (CC BY 4.0).
 *
 * Existing rows are left untouched, so this is safe to re-run. To pick up a
 * refreshed dump, delete the affected cities first — city rows are referenced
 * by reviews and visits, so a blind delete-all would take those with it.
 */
async function main() {
  const cities = loadCities();
  const existing = await prisma.city.count();
  console.log(`Seeding ${cities.length} cities (${existing} already present)…`);

  let inserted = 0;
  for (let start = 0; start < cities.length; start += CHUNK_SIZE) {
    const result = await prisma.city.createMany({
      data: cities.slice(start, start + CHUNK_SIZE),
      skipDuplicates: true,
    });
    inserted += result.count;
  }

  console.log(`Done. Inserted ${inserted} new cities.`);
}

// A failed seed must not report success — CI and deploy pipelines only
// look at the exit code.
main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
